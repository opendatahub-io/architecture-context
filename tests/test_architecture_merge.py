@pytest.mark.parametrize(
    ("action", "analyzer_value", "candidate_value", "evidence", "message"),
    [
        ("add", "unexpected", "<empty>", "worker.py:10", "requires Analyzer"),
        ("delete", "<empty>", "unexpected", "worker.py:10", "requires Analyzer"),
        ("add", "<empty>", "<empty>", "/tmp/worker.py:10", "repository-relative"),
        ("add", "<empty>", "<empty>", "../worker.py:10", "repository-relative"),
        ("add", "<empty>", "<empty>", "worker.py:20-10", "range is reversed"),
    ],
)
def test_change_record_parser_rejects_invalid_row_evidence(
    action: str,
    analyzer_value: str,
    candidate_value: str,
    evidence: str,
    message: str,
):
    records, errors = parse_change_records(
        change_record(
            (
                action,
                "architecture_components",
                "worker",
                "*",
                analyzer_value,
                candidate_value,
                "Worker evidence",
                evidence,
            )
        )
    )

    assert records == []
    assert any(message in error for error in errors)


