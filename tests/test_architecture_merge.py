def test_source_adjudicated_addition_is_rejected():
    analyzer = document([("api", "Service", "API")])
    candidate = document([("api", "Service", "API"), ("worker", "Service", "Jobs")])
    changes = change_record(
        (
            "add",
            "architecture_components",
            "worker",
            "*",
            "<empty>",
            "<empty>",
            "Worker entry point is deployed",
            "worker.py:10-20",
        )
    )

    result = merge_architecture_documents(
        analyzer,
        candidate,
        changes_text=changes,
        rejected_additions={
            ("architecture_components", ("worker",)): (
                "The worker is test-only",
                ("tests/worker.py:4-12",),
            )
        },
    )

    assert "| worker | Service | Jobs |" not in result.text
    rejected = [
        decision
        for decision in result.decisions
        if decision.status == "rejected"
        and decision.key == ("worker",)
    ]
    assert len(rejected) == 1
    assert rejected[0].reason == "The worker is test-only"
    assert rejected[0].evidence == ("tests/worker.py:4-12",)


def test_rejected_addition_loader_normalizes_persisted_row_keys(tmp_path: Path):
    adjudications = tmp_path / "adjudications.json"
    adjudications.write_text(
        json.dumps(
            {
                "accepted_analyzer_absences": [
                    {
                        "component": "example",
                        "category": "architecture_components",
                        "key": [" Batch-Apiserver "],
                        "reason": "The build artifact has a more precise name.",
                        "evidence": ["Dockerfile:20"],
                    }
                ]
            }
        )
    )

    rejected = load_rejected_additions("example", path=adjudications)

    assert rejected == {
        ("architecture_components", ("batch-apiserver",)): (
            "The build artifact has a more precise name.",
            ("Dockerfile:20",),
        )
    }


